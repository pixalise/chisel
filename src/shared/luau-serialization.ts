export const LUAU_HEADER = "--!strict\n-- Generated by Chisel. Do not edit.\n";

export function luauString(value: string): string {
  let result = '"';
  for (const character of value) {
    const code = character.charCodeAt(0);
    if (character === "\\") result += "\\\\";
    else if (character === '"') result += '\\"';
    else if (code < 32 || code === 127) result += `\\${code.toString().padStart(3, "0")}`;
    else result += character;
  }
  return `${result}"`;
}

export function luauValue(value: unknown): string {
  if (value === null) throw new Error("Luau tables cannot preserve JSON null; use an explicit authored value.");
  if (typeof value === "string") return luauString(value);
  if (typeof value === "boolean") return String(value);
  if (typeof value === "number" && Number.isFinite(value)) return String(value);
  if (Array.isArray(value)) return `table.freeze({ ${value.map(luauValue).join(", ")} })`;
  if (typeof value === "object" && value !== null) {
    return `table.freeze({ ${Object.entries(value)
      .map(([key, entry]) => `[${luauString(key)}] = ${luauValue(entry)}`)
      .join(", ")} })`;
  }
  throw new Error(`Cannot export ${String(value)} to Luau.`);
}

export interface LuauExportFile {
  content: string;
  path: string;
}
