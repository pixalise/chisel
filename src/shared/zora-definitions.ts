export const assetGroups: Record<AssetCategoryEnum, string> = {
  MESH: "Models",
  TERRAIN_TEXTURE: "PbrTextures",
  HDRI: "Environments",
  UI: "Ui",
  IMAGE: "Images",
  TILESET: "Tilesets",
  AUDIO: "Audio",
  FONT: "Fonts",
  SHADER: "Shaders",
  DATA: "Data",
  OTHER: "Other",
}
const reserved = new Set(
  `abstract alias align asm assert auto body bool break byte case cast catch cdouble cent cfloat char class const continue creal dchar debug default delegate delete deprecated do double else enum export extern false final finally float for foreach foreach_reverse function goto idouble if ifloat immutable import in inout int interface invariant ireal is lazy long macro mixin module new nothrow null out override package pragma private protected public pure real ref return scope shared short static struct super switch synchronized template this throw true try typedef typeid typeof ubyte ucent uint ulong union unittest ushort version void wchar while with __gshared __traits __vector __parameters init sizeof alignof mangleof stringof tupleof get all slug`.split(
    " "
  )
)

export function fieldName(name: string): string {
  const result = camelCase(name)
  if (!/^[A-Za-z][A-Za-z0-9]*$/.test(result) || reserved.has(result)) {
    throw new Error(`Invalid generated D field name: ${name}`)
  }
  return result
}
export function tableName(table: AnyDataTable): string {
  return upperFirst(fieldName(table.name))
}
export function assetConstants(assets: Asset[]): Record<string, Record<string, string>> {
  const groups: Record<string, Record<string, string>> = Object.create(null)
  for (const group of Object.values(assetGroups)) {
    groups[group] = Object.create(null)
  }
  for (const asset of assets) {
    groups[assetGroups[asset.category]][asset.id] = asset.id
  }
  return groups
}
export function exportedRows(table: AnyDataTable): Record<string, Record<string, unknown>> {
  assertUnique(
    table.columns.map((column) => fieldName(column.name)),
    `field in ${table.name}`
  )
  const rows: Record<string, Record<string, unknown>> = Object.create(null)
  for (const row of table.rows) {
    rows[row.slug] = Object.fromEntries([
      ["slug", row.slug],
      ...table.columns.map((column) => [fieldName(column.name), valueFor(row, column)]),
    ])
  }
  return rows
}
function dType(column: DataColumnDefinition): string {
  const types: Record<ColumnType, string> = {
    string: "string",
    text: "string",
    enum: "string",
    ref: "string",
    assetRef: "string",
    translationRef: "string",
    integer: "long",
    decimal: "double",
    range: "double",
    boolean: "bool",
    enumArray: "string[]",
    arrayRef: "string[]",
    color: "string",
    vector2: "double[2]",
    vector3: "double[3]",
    vector4: "double[4]",
    json: "JSONValue",
  }
  if (!column.required && column.type !== ColumnType.JSON) {
    return `Nullable!(${types[column.type]})`
  }
  return types[column.type]
}
export function renderDefinitions(
  tables: AnyDataTable[],
  assets: Asset[],
  localization: LocalizationDocument
): ZoraExportFile[] {
  const lines = [
    "// Generated by Mrak. Do not edit.",
    "module zora_content.definitions;",
    "import std.json : JSONValue;",
    "import engine.assets.content : Content;",
    "import std.typecons : Nullable;",
    "struct Assets",
    "{",
  ]
  for (const [group, entries] of Object.entries(assetConstants(assets))) {
    lines.push(`    struct ${group}`, "    {")
    for (const [name, slug] of Object.entries(entries)) {
      lines.push(`        enum string ${name} = ${JSON.stringify(slug)};`)
    }
    lines.push("    }")
  }
  lines.push("}", "struct Tables", "{")
  const annotations = [
    "---@meta",
    "-- Generated by Mrak. Do not edit.",
    "---@class MrakNull",
    "---@class MrakAssets",
  ]
  for (const group of Object.keys(assetConstants(assets))) {
    annotations.push(`---@field ${group} MrakAssets${group}`)
    // Group declarations are emitted below the Assets annotation.
  }
  annotations.push("Assets = {}")
  for (const [group, entries] of Object.entries(assetConstants(assets))) {
    annotations.push(`---@class MrakAssets${group}`)
    for (const name of Object.keys(entries)) {
      annotations.push(`---@field ${name} string`)
    }
    annotations.push(`Assets.${group} = {}`)
  }
  const tableFields: string[] = []
  for (const table of tables) {
    const name = tableName(table)
    exportedRows(table)
    lines.push(
      `    struct ${name}`,
      "    {",
      "        struct Row",
      "        {",
      "            string slug;"
    )
    annotations.push(`---@class Mrak${name}Row`, "---@field slug string")
    for (const column of table.columns) {
      lines.push(`            ${dType(column)} ${fieldName(column.name)};`)
      let luaType = "string"
      if ([ColumnType.INTEGER, ColumnType.DECIMAL, ColumnType.RANGE].includes(column.type)) {
        luaType = "number"
      }
      if (column.type === ColumnType.BOOLEAN) {
        luaType = "boolean"
      }
      if (
        column.type.startsWith("vector") ||
        column.type.endsWith("Array") ||
        column.type === ColumnType.ARRAY_REF
      ) {
        luaType = "table"
      }
      if (column.type === ColumnType.JSON) {
        luaType = "any"
      }
      if (!column.required) {
        luaType += "|MrakNull"
      }
      annotations.push(`---@field ${fieldName(column.name)} ${luaType}`)
    }
    lines.push("        }")
    for (const row of table.rows) {
      lines.push(
        `        static @property immutable(Row) ${row.slug}() { return get(${JSON.stringify(row.slug)}); }`
      )
    }
    lines.push(
      `        static @property immutable(Row)[] all() { return Content.definitions!Row(${JSON.stringify(name)}); }`,
      `        static immutable(Row) get(string slug) { return Content.definition!Row(${JSON.stringify(name)}, slug); }`,
      "    }"
    )
    annotations.push(`---@class Mrak${name}`)
    for (const row of table.rows) {
      annotations.push(`---@field ${row.slug} Mrak${name}Row`)
    }
    tableFields.push(`---@field ${name} Mrak${name}`)
  }
  lines.push("}", "struct Localization", "{", "    struct Keys", "    {")
  for (const key of localization.keys) {
    lines.push(
      `        enum string ${key.path.replaceAll(".", "_")} = ${JSON.stringify(key.path)};`
    )
  }
  lines.push(
    "    }",
    "    static @property immutable(JSONValue) data() { return Content.localization(); }",
    "}",
    ""
  )
  annotations.push(
    "---@class MrakTables",
    ...tableFields,
    "Tables = {}",
    "---@class MrakLocalization",
    "---@field Keys table<string, string>",
    "---@field keys table[]",
    "---@field locales string[]",
    "---@field defaultLocale string",
    "Localization = {}",
    "---@class MrakContent",
    "---@field NULL MrakNull",
    "---@field Assets MrakAssets",
    "---@field Tables MrakTables",
    "---@field Localization MrakLocalization",
    "Content = {}",
    ""
  )
  return [
    { path: "ZoraData/d/zora_content/definitions.d", content: lines.join("\n") },
    { path: "ZoraData/lua/definitions.meta.lua", content: annotations.join("\n") },
  ]
}
