export function luaString(value: string): string {
  let result = '"'
  for (const character of value) {
    const code = character.charCodeAt(0)
    if (character === "\\" || character === '"') {
      result += `\\${character}`
    } else if (code < 32 || code === 127) {
      result += `\\${code.toString().padStart(3, "0")}`
    } else {
      result += character
    }
  }
  return `${result}"`
}

export function luaValue(value: unknown): string {
  if (value === null) {
    return "NULL"
  }
  if (typeof value === "string") {
    return luaString(value)
  }
  if (typeof value === "boolean" || (typeof value === "number" && Number.isFinite(value))) {
    return String(value)
  }
  if (Array.isArray(value)) {
    return `readonly({ ${value.map(luaValue).join(", ")} })`
  }
  if (typeof value === "object" && value !== null) {
    return `readonly({ ${Object.entries(value)
      .map((entry) => {
        const [key, field] = entry
        return `[${luaString(key)}] = ${luaValue(field)}`
      })
      .join(", ")} })`
  }
  throw new Error(`Cannot export ${String(value)} to Lua.`)
}

